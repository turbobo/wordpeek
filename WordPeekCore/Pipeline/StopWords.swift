import Foundation

/// 打字学英语场景下不值得弹出的高频功能词。
///
/// 过滤原则：语法功能词（连接词 / 代词 / 助词 / 时态词）过滤；
/// 实词（名词 / 动词 / 形容词）保留。目的是避免浮窗刷屏。
public enum StopWords {

    /// 多字功能词（2 字及以上）：无论是否在词典中，均不展示
    public static let multi: Set<String> = [
        // 连接 / 逻辑
        "因为", "所以", "但是", "如果", "不过", "而且", "并且", "然后", "接着", "于是", "即使", "虽然", "而是", "或者", "还是", "要是",
        // 情态 / 时态
        "可以", "已经", "正在", "可能", "应该", "需要", "必须", "能够", "一直", "总是", "经常", "偶尔", "马上", "立刻", "已经",
        // 人称 / 指示
        "我们", "你们", "他们", "她们", "它们", "咱们", "大家", "自己", "别人",
        "什么", "怎么", "为什么", "这里", "那里", "这个", "那个", "这些", "那些", "哪个", "哪些", "这种", "那种", "这样", "那样",
        // 数量 / 程度
        "一个", "一下", "一些", "一次", "一起", "一样", "一种", "一点", "有点", "非常", "特别", "真的", "其实", "当然", "肯定", "一定",
        // 否定 / 系动词
        "不是", "没有", "就是", "只是", "只有", "还有",
        // 时间（高频、低学习价值）
        "时候", "现在", "今天", "明天", "昨天", "每天", "刚才", "以后", "以前", "之后", "之前",
        // 方位
        "上面", "下面", "里面", "外面", "前面", "后面", "左边", "右边", "中间", "旁边",
    ]

    /// 单字功能词：仅在用户开启"显示单字词"时参与过滤
    public static let single: Set<String> = [
        "的", "了", "是", "在", "我", "你", "他", "她", "它", "们", "咱", "不", "没", "就", "也", "很", "都",
        "和", "与", "及", "或", "而", "但", "吗", "呢", "吧", "啊", "哦", "嗯", "呀", "哇", "啦", "之", "其",
        "此", "把", "被", "给", "让", "向", "从", "到", "对", "为", "以", "于", "会", "能", "要", "想", "说",
        "看", "去", "来", "上", "下", "里", "外", "中", "大", "小", "多", "少", "好", "一", "二", "三", "四",
        "五", "六", "七", "八", "九", "十", "个", "这", "那", "哪", "谁", "啥", "嘛", "着", "过", "得", "地",
        "又", "还", "只", "更", "最", "太", "真", "才", "刚", "已", "曾", "将", "且", "因", "由",
    ]

    /// 多字词是否命中停用表
    public static func isMultiStopWord(_ word: String) -> Bool {
        multi.contains(word)
    }

    /// 单字是否命中停用表
    public static func isSingleStopWord(_ word: String) -> Bool {
        single.contains(word)
    }

    /// 通用判定：单字 / 多字分别查对应表
    public static func contains(_ word: String) -> Bool {
        word.count >= 2 ? multi.contains(word) : single.contains(word)
    }
}
